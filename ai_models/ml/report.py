"""Render the evaluation report (markdown + figures) from training results."""
from __future__ import annotations

import math
from pathlib import Path

import numpy as np

HGB = "HistGradientBoosting (calibrated)"
TITLES = {
    "thunder_1h": "Thunderstorm within 1 h",
    "thunder_3h": "Thunderstorm within 3 h",
    "wind_1h": "Strong wind (>= 25 kt) within 1 h",
    "wind_3h": "Strong wind (>= 25 kt) within 3 h",
}


def _f(x, nd=3):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "n/a"
    return f"{x:.{nd}f}"


def _ci(ci, nd=3):
    return f"[{ci[0]:.{nd}f}, {ci[1]:.{nd}f}]"


# Categorical colours follow the method (entity), never its rank, and are the
# first five slots of a palette validated for colour-vision-deficiency separation.
SURFACE, INK, MUTED, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"
SERIES = {
    HGB: ("HGB (calibrated)", "#2a78d6", "-", 2.4),
    "Logistic regression": ("Logistic regression", "#eb6834", "-", 1.5),
    "Persistence": ("Persistence", "#1baf7a", "--", 1.5),
    "Persistence + METAR trend": ("Persistence + trend", "#eda100", "-.", 1.5),
    "Climatology (station x month x 3h)": ("Climatology", "#e87ba4", ":", 1.8),
}


def _style(ax, title, xlabel, ylabel):
    ax.set_facecolor(SURFACE)
    ax.set_title(title, fontsize=10, color=INK, loc="left")
    ax.set_xlabel(xlabel, fontsize=9, color=MUTED)
    ax.set_ylabel(ylabel, fontsize=9, color=MUTED)
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)
    ax.grid(True, color=GRID, lw=0.8)
    ax.set_axisbelow(True)
    ax.tick_params(colors=MUTED, labelsize=8, length=0)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(GRID)


def write_figures(curves: dict, results: dict, fig_dir: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from sklearn.metrics import precision_recall_curve

    fig_dir.mkdir(parents=True, exist_ok=True)
    names = list(curves)

    fig, axes = plt.subplots(2, 2, figsize=(10.5, 8.6), facecolor=SURFACE)
    for ax, name in zip(axes.ravel(), names):
        y, preds = curves[name]["y"], curves[name]["preds"]
        for key, (label, color, ls, lw) in reversed(list(SERIES.items())):
            if key in preds:
                p, r, _ = precision_recall_curve(y, preds[key])
                ap = results[name]["metrics"][key]["pr_auc"]
                ax.step(r, p, where="post", color=color, ls=ls, lw=lw,
                        label=f"{label}  (PR-AUC {ap:.2f})")
        ax.axhline(y.mean(), color=MUTED, lw=0.8)
        ax.annotate(f"no skill = prevalence {y.mean():.2%}", (0.99, y.mean()), xytext=(0, 3),
                    textcoords="offset points", ha="right", fontsize=7.5, color=MUTED)
        _style(ax, f"{TITLES[name]}", "Recall", "Precision")
        handles, labels = ax.get_legend_handles_labels()
        ax.legend(handles[::-1], labels[::-1], fontsize=7.5, loc="upper right", frameon=False,
                  labelcolor=INK)
    fig.suptitle("Precision-recall on the held-out test period (2023-2024)", fontsize=11,
                 color=INK, x=0.01, ha="left")
    fig.tight_layout(rect=(0, 0, 1, 0.97))
    fig.savefig(fig_dir / "pr_curves.png", dpi=140, facecolor=SURFACE)
    plt.close(fig)

    fig, axes = plt.subplots(1, len(names), figsize=(3.6 * len(names), 3.9), facecolor=SURFACE,
                             squeeze=False)
    for ax, name in zip(axes[0], names):
        ax.plot([0, 1], [0, 1], color=MUTED, lw=0.8)
        for key, label, color, ls, marker in (
                ("uncalibrated", "before calibration", "#eb6834", "--", "o"),
                ("calibrated", "after isotonic calibration", "#2a78d6", "-", "s")):
            rows = results[name]["reliability"][key]
            ax.plot([r[3] for r in rows], [r[4] for r in rows], color=color, ls=ls, lw=2,
                    marker=marker, ms=5, mec=SURFACE, mew=1, label=label)
        _style(ax, TITLES[name], "Mean forecast probability", "Observed frequency")
        ax.set_aspect("equal")
    axes[0][0].legend(fontsize=7.5, loc="upper left", frameon=False, labelcolor=INK)
    fig.suptitle("Reliability of the gradient-boosting model on test (diagonal = perfect)",
                 fontsize=11, color=INK, x=0.01, ha="left")
    fig.tight_layout(rect=(0, 0, 1, 0.94))
    fig.savefig(fig_dir / "reliability.png", dpi=140, facecolor=SURFACE)
    plt.close(fig)


def write_report(path: Path, meta: dict, data_summary) -> None:
    L = []
    add = L.append
    d = meta["data"]
    add("# AirfieldShield - model evaluation report")
    add("")
    add("> Generated by `python -m ai_models.ml.train`; do not edit by hand. "
        f"Run at {meta['created_utc']} (code commit `{meta['git_commit']}`, seed {meta['seed']})."
        + (" **QUICK MODE - not the reference run.**" if meta.get("quick_mode") else ""))
    add("")
    add("All numbers below are computed on **real archived METAR observations**; no synthetic "
        "data is used anywhere in training or evaluation.")
    add("")
    add("## 1. Data")
    add("")
    add(f"- Source: {d['source']} (public, no API key), routine + special reports.")
    add(f"- Period: {d['first'][:10]} to {d['last'][:10]} (UTC), aggregated to hourly buckets "
        "`(h-1h, h]`.")
    add(f"- File: `data/{d['file']}`, sha256 `{d['sha256'][:16]}...`, "
        f"{d['station_hours']:,} station-hours with at least one report.")
    add(f"- Hazards: *thunderstorm* = TS/VCTS present-weather group in the observation body of any "
        f"report; *strong wind* = sustained wind or gust >= {meta['strong_wind_threshold_kt']} kt.")
    add("")
    add("| Station | Airfield | Hours | Report coverage | TS hours | Strong-wind hours (>=25 kt) | Gale hours (>=34 kt) |")
    add("|---|---|---:|---:|---:|---:|---:|")
    for r in data_summary.itertuples():
        add(f"| {r.station} | {r.name} | {r.hours:,} | {r.coverage:.1%} | {r.ts_hours:,} | "
            f"{r.strong_wind_hours:,} | {r.gale_hours:,} |")
    add("")
    qc = (meta.get("data_qc") or {})
    if qc:
        keys = [k for k in next(iter(qc.values())) if k != "reports"]
        add("")
        add("Quality control. Indian METARs are typed by hand and contain typos such as "
            "`070064KT` or `09006G46KT` in fog. Each rule below uses only the report itself and "
            "the previous report, so the same procedure runs at serving time. Flagged values are "
            "set to missing, not dropped. Counts are individual reports:")
        add("")
        add("| Station | Reports | " + " | ".join(k.replace("_", " ") for k in keys) + " |")
        add("|---|---:|" + "---:|" * len(keys))
        for st, row in qc.items():
            add(f"| {st} | {row['reports']:,} | " + " | ".join(f"{row[k]:,}" for k in keys) + " |")
        add("")
    add("True gale-force wind (>= 34 kt) is too rare at these airfields to train or evaluate a "
        "classifier (see last column), so the wind hazard is defined at 25 kt.")
    add("")
    add("## 2. Protocol")
    add("")
    s = meta["split"]
    add(f"- Chronological split: train `{s['train']}`, validation `{s['validation']}`, "
        f"test `{s['test']}`. Rows whose label window crosses a boundary are purged.")
    add("- Features at hour `h` use only reports valid at or before `h`; labels cover `(h, h+H]`. "
        "A label is 0 only if every hour of the window has a report, otherwise the row is dropped.")
    add("- Validation year is used for boosting-iteration selection, class-weight selection, "
        "isotonic calibration and alert thresholds. Test years are used once, for this report.")
    add("- 95% confidence intervals: percentile bootstrap resampling whole station-days "
        "(hourly samples are autocorrelated), paired across methods.")
    add("- Metrics: PR-AUC (average precision), ROC-AUC, Brier score, Brier skill score (BSS) "
        "relative to climatology, expected calibration error (ECE, 10 equal-mass bins).")
    add("")
    add("## 3. Results on the held-out test period")
    for name, res in meta["targets"].items():
        add("")
        add(f"### 3.{list(meta['targets']).index(name) + 1} {TITLES[name]} (`{name}`)")
        add("")
        n, pos = res["n"], res["positives"]
        add(f"Samples (positives): train {n['train']:,} ({pos['train']:,}), "
            f"validation {n['val']:,} ({pos['val']:,}), test {n['test']:,} ({pos['test']:,}); "
            f"test prevalence {pos['test'] / n['test']:.2%}.")
        add("")
        add("| Method | PR-AUC | 95% CI | ROC-AUC | Brier | BSS vs clim. | ECE |")
        add("|---|---:|---:|---:|---:|---:|---:|")
        for label, m in res["metrics"].items():
            b = "**" if label == HGB else ""
            add(f"| {b}{label}{b} | {b}{_f(m['pr_auc'])}{b} | {_ci(m['pr_auc_ci'])} | "
                f"{_f(m['roc_auc'])} | {_f(m['brier'], 4)} | {_f(m.get('bss'))} | {_f(m['ece'], 4)} |")
        add("")
        add("Paired bootstrap, calibrated HGB minus other method (PR-AUC difference > 0 and "
            "Brier difference < 0 favour HGB; an interval containing 0 is not significant):")
        add("")
        add("| Compared with | PR-AUC diff 95% CI | Brier diff 95% CI |")
        add("|---|---:|---:|")
        for label, p in res["paired_vs_hgb"].items():
            add(f"| {label} | {_ci(p['pr_auc_diff_ci'])} | {_ci(p['brier_diff_ci'], 5)} |")
        add("")
        add("Operating points (threshold chosen on validation to reach a precision target with "
            "maximum recall, then applied unchanged to test). These thresholds drive the alert levels "
            "YELLOW / ORANGE / RED.")
        add("")
        add("| Precision target (val) | Threshold | Val precision | Val recall | Test precision | Test recall | Test alerts |")
        add("|---:|---:|---:|---:|---:|---:|---:|")
        for o in res["operating_points"]:
            add(f"| {o['precision_target']:.2f} | {_f(o['threshold'])} | {_f(o['val_precision'])} | "
                f"{_f(o['val_recall'])} | {_f(o['test_precision'])} | {_f(o['test_recall'])} | "
                f"{o['test_alerts']:,} |")
        on = res["onset"]
        add("")
        add(f"Onset-only subset (hazard absent now and during the previous 3 h; {on['n']:,} rows, "
            f"{on['positives']:,} positives, prevalence {on['prevalence']:.2%}) - the harder and "
            "operationally more valuable case, where persistence carries no information:")
        add("")
        add("| Method | PR-AUC (onset only) |")
        add("|---|---:|")
        for label, v in on["pr_auc"].items():
            add(f"| {label} | {_f(v)} |")
        add("")
        add("Per station (calibrated HGB; stations with < 5 test positives omitted):")
        add("")
        add("| Station | Test rows | Positives | PR-AUC | ROC-AUC | Brier | BSS vs clim. |")
        add("|---|---:|---:|---:|---:|---:|---:|")
        for r in res["per_station"]:
            add(f"| {r['station']} | {r['n']:,} | {r['positives']:,} | {_f(r['pr_auc'])} | "
                f"{_f(r['roc_auc'])} | {_f(r['brier'], 4)} | {_f(r.get('bss'))} |")
        add("")
        sel = res["hgb_selection"]
        add("Class-imbalance handling (selected on validation PR-AUC): "
            + "; ".join(f"`class_weight={k}` -> val PR-AUC {_f(v['val_pr_auc'])} at "
                        f"{v['best_iter']} iterations" for k, v in sel.items())
            + f". Chosen: `{res['chosen_class_weight']}`. Probabilities are re-calibrated with "
              "isotonic regression on validation in either case.")
        add("")
        add("Top-10 permutation importances (drop in test PR-AUC, mean +/- sd of 3 repeats): "
            + ", ".join(f"`{f}` {m:.3f}+/-{s:.3f}" for f, m, s in res["importance"]) + ".")
        add("")
        add("Reliability of the calibrated model on test:")
        add("")
        add("| Forecast bin | n | Mean forecast | Observed frequency |")
        add("|---|---:|---:|---:|")
        for lo, hi, cnt, mp, of in res["reliability"]["calibrated"]:
            add(f"| {lo:.2f}-{hi:.2f} | {cnt:,} | {mp:.3f} | {of:.3f} |")
    add("")
    add("## 4. Figures")
    add("")
    add("![Precision-recall curves](figures/pr_curves.png)")
    add("")
    add("![Reliability diagrams](figures/reliability.png)")
    add("")
    add("## 5. Environment")
    add("")
    add(", ".join(f"{k} {v}" for k, v in meta["versions"].items()) + ".")
    add("")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(L), encoding="utf-8", newline="\n")
